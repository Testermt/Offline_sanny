#!/usr/bin/env python3
"""Builds a classes.db for the sa_mobile edit mode.
Sanny Builder ships an EMPTY classes.db for sa_mobile (6 bytes), so Player.Defined($P) style code does not compile there.
This script takes the PC classes (data/sa/classes.db), keeps only the members whose opcode exists in the sa_mobile opcode list
(SASCM.INI of sa + SASCM.Mobile.ini + SASCM.CLEO.ini + sa_mobile/SASCM.ini) and appends a Widget class for the mobile-only widget commands.
usage: gen_mobile_classes.py <sanny data dir> > <sanny data dir>/sa_mobile/classes.db"""
import re, sys, os

def find(d, name):
    for f in os.listdir(d):
        if f.lower() == name.lower(): return os.path.join(d, f)

root = sys.argv[1]
ops = set()
for sub, files in (('sa', ['SASCM.INI']), ('sa_mobile', ['SASCM.Mobile.ini', 'SASCM.CLEO.ini', 'SASCM.ini'])):
    for fn in files:
        p = find(os.path.join(root, sub), fn)
        if not p: continue
        for l in open(p, encoding='latin1').read().splitlines():
            m = re.match(r'^([0-9A-Fa-f]{4})=', l)
            if m: ops.add(int(m.group(1), 16))

src = open(find(os.path.join(root, 'sa'), 'classes.db'), encoding='latin1').read().replace('\r', '').split('\n')

WIDGET = '''$Widget
$BEGIN
; properties
^Value,[0A5E,=,1,0,0],[0A5A,=,2,0,0],("Widget%h" "Value%f")
^EquippedItem,[0A6C,=,1,0,0],("Widget%h" "Item%i")
^Texture,[0A6E,=,1,0,0],("Widget%h" "Texture%v")

; procs
Delete,0A6B,0,0,("Widget%h")
AddFlag,0A60,0,0,("Widget%h" "Flag%i")
RemoveFlag,0A61,0,0,("Widget%h" "Flag%i")
AddButtonFlag,0A62,0,0,("Widget%h" "Flag%i")
RemoveButtonFlag,0A63,0,0,("Widget%h" "Flag%i")
StoreValue2,0A5B,0,0,("Widget%h" "Value1: Variable" "Value2: Variable")
SetValue3,0A73,0,0,("Widget%h" "Value1%f" "Value2%f" "Value3%f")
SetSliderRange,0A5F,0,0,("Widget%h" "Min%f" "Max%f")
StorePosition,0A5D,0,0,("Widget%h" "X: Variable" "Y: Variable" "ScaleX: Variable" "ScaleY: Variable")

; conditions
IsPressed,0A51,1,0,("Widget%h")
IsReleased,0A52,1,0,("Widget%h")
IsDoubleTapped,0A53,1,0,("Widget%h")
IsSwiped,0A54,1,0,("Widget%h")
IsSwipedLeft,0A55,1,0,("Widget%h")
IsSwipedRight,0A56,1,0,("Widget%h")
$END
'''

def entry_ok(op_text): return int(op_text, 16) in ops

# first pass: split into the preamble (up to #CLASSES) and class blocks
out_pre, blocks, cur = [], [], None
state = 'pre'
for l in src:
    if state == 'pre':
        out_pre.append(l)
        if l.strip() == '#CLASSES': state = 'cls'
        continue
    if l.strip() == '#EOF': break
    if l.startswith('$') and l.strip().upper() not in ('$BEGIN', '$END'):
        cur = {'name': l[1:].strip(), 'lines': [l], 'members': 0}; blocks.append(cur); continue
    if cur is None: continue
    s = l.strip()
    if s.upper() == '$BEGIN' or s.upper() == '$END' or s == '' or s.startswith(';'):
        cur['lines'].append(l); continue
    if s.startswith('^'):  # ^Name,[op,math,pos,type,help],...,("hint")
        groups = re.findall(r'\[[^\]]*\]', s)
        keep = [g for g in groups if entry_ok(g[1:-1].split(',')[0])]
        if not keep: continue
        head = s[:s.index('[')]
        tail = s[s.rindex(']') + 1:]
        cur['lines'].append(head + ','.join(keep) + tail); cur['members'] += 1
        # head ends with "," already
        continue
    m = re.match(r'^[A-Za-z_]\w*,([0-9A-Fa-f]{4}),', s)
    if m and entry_ok(m.group(1)):
        cur['lines'].append(l); cur['members'] += 1

kept = [b for b in blocks if b['members'] > 0]
dropped = [b['name'] for b in blocks if b['members'] == 0]
names = [b['name'] for b in kept] + ['Widget']

# preamble: rebuild the class list, drop deprecated enums of dropped classes
pre = []
in_list = False
for l in out_pre:
    s = l.strip()
    if s == '#CLASSESLIST':
        pre.append(l); in_list = True
        pre.extend(names); pre.append('')
        continue
    if in_list:
        if s.startswith('; ----') or s.startswith(';\t') or (s.startswith(';') and 'keywords' in s): in_list = False
        else: continue
    m = re.match(r'^([A-Za-z_]\w*)\.\w+\.\d+\s*=', s)
    if m and m.group(1).lower() in [d.lower() for d in dropped]: continue
    pre.append(l)

out = []
out.append('; Generated by tools/gen_mobile_classes.py: PC classes (data/sa/classes.db) restricted to the opcodes of the sa_mobile mode + a Widget class.')
out.extend(pre)
for b in kept:
    out.extend(b['lines']); out.append('')
out.extend(WIDGET.split('\n'))
out.append('#EOF')
sys.stdout.write('\n'.join(out) + '\n')
sys.stderr.write('kept classes: %s | dropped (no member left): %s | Widget added\n' % (', '.join(b['name'] for b in kept), ', '.join(dropped) or '-'))
